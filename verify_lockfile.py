"""Verifies vpython.toml and PEP 723 specification files against uv.lock files.

This script parses Python virtual environment specification files (vpython.toml
and inline PEP 723 script blocks) and ensures that all declared dependencies are
present and satisfied in the companion uv.lock lockfile. It expects multi-target
universal lockfiles generated by uv (e.g. via `uv pip compile`).
"""

import os
import re
import sys
from typing import Any

try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib
    except ImportError:
        tomllib = None

try:
    from packaging.requirements import Requirement
    from packaging.specifiers import SpecifierSet
    from packaging.version import Version
except ImportError:
    Requirement = None
    SpecifierSet = None
    Version = None


def normalize_name(name: str) -> str:
    """Normalizes a Python package name per PEP 503 and PEP 685.

    Strips extras (e.g. requests[security] -> requests) and replaces runs of
    hyphens, underscores, and dots with a single hyphen.

    Args:
        name: The package name string to normalize.

    Returns:
        The normalized lowercase package name.
    """
    # Strip extras e.g. requests[security] -> requests
    name = re.sub(r"\[.*?\]", "", name).strip()
    # PEP 503 / PEP 685: replace runs of -, _, and . with a single hyphen (-)
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_version(ver_str: str) -> Any | tuple[int, ...]:
    """Parses a version string into a comparable Version object or tuple.

    Uses packaging.version.Version if available, otherwise falls back to a
    tuple representation with PEP 440 pre-release and post-release tag weights.

    Args:
        ver_str: Version string (e.g., "1.2.3", "2.0.0b1", "1.0.0.post1").

    Returns:
        A packaging.version.Version object or a comparable tuple.
    """
    if Version is not None:
        try:
            return Version(ver_str)
        except Exception:
            pass

    # Fallback version parser with PEP 440 tag weights:
    # dev: 0, a: 1, b: 2, rc: 3, final: 4, post: 5
    tag_weights = {
        "dev": 0,
        "a": 1,
        "alpha": 1,
        "b": 2,
        "beta": 2,
        "c": 3,
        "rc": 3,
        "post": 5,
    }

    m = re.match(
        r"^(\d+(?:\.\d+)*)(?:[\.\-]?([a-zA-Z]+)[\.\-]?(\d+)?)*", ver_str
    )
    if m and m.group(1):
        nums = tuple(int(x) for x in m.group(1).split("."))
        tag = m.group(2)
        if tag:
            tag_name = tag.lower()
            weight = tag_weights.get(tag_name, 0)
            pre_num = int(m.group(3)) if m.group(3) else 0
            return nums + (weight, pre_num)
        return nums + (4, 0)  # Final release weight = 4

    parts = tuple(int(x) for x in re.findall(r"\d+", ver_str))
    return parts + (4, 0)


def compare_versions(v1: str, op: str, v2: str) -> bool:
    """Compares two version strings given a comparison operator.

    Args:
        v1: The version string to compare (e.g. locked version "2.31.0").
        op: Comparison operator (e.g. "==", ">=", "<=", ">", "<", "!=", "~=").
        v2: The target requirement version string (e.g. "2.28.0").

    Returns:
        True if v1 satisfies (v1 op v2), False otherwise.
    """
    if SpecifierSet is not None and Version is not None:
        try:
            spec = SpecifierSet(f"{op}{v2}")
            ver = Version(v1)
            return spec.contains(ver, prereleases=True)
        except Exception:
            pass

    if op == "~=":
        parts = [int(x) for x in re.findall(r"\d+", v2)]
        if len(parts) >= 2:
            upper_parts = list(parts[:-1])
            upper_parts[-1] += 1
            upper_v = ".".join(str(x) for x in upper_parts)
            parsed_v1 = parse_version(v1)
            is_final_or_post = (
                isinstance(parsed_v1, tuple) and parsed_v1[-2] >= 4
            )
            return (
                compare_versions(v1, ">=", v2)
                and compare_versions(v1, "<", upper_v)
                and is_final_or_post
            )
        return compare_versions(v1, ">=", v2)

    t1 = parse_version(v1)
    t2 = parse_version(v2)

    # Pad shorter numeric tuple before comparing
    if isinstance(t1, tuple) and isinstance(t2, tuple):
        max_len = max(len(t1), len(t2))
        t1 = t1[:-2] + (0,) * (max_len - len(t1)) + t1[-2:]
        t2 = t2[:-2] + (0,) * (max_len - len(t2)) + t2[-2:]

    if op == "==":
        return t1 == t2
    if op == ">=":
        return t1 >= t2
    if op == "<=":
        return t1 <= t2
    if op == ">":
        return t1 > t2
    if op == "<":
        return t1 < t2
    if op == "!=":
        return t1 != t2
    return False


def parse_vpython_toml(path: str) -> list[str] | None:
    """Parses a vpython.toml file and extracts its dependencies list.

    Args:
        path: Path to the vpython.toml file.

    Returns:
        List of dependency requirement strings, or None if parsing failed.
    """
    if tomllib is None:
        print("Error: tomllib module not available.", file=sys.stderr)
        return None
    try:
        with open(path, "rb") as f:
            data = tomllib.load(f)
        if not isinstance(data, dict):
            print(
                f"Error: Expected dictionary root in TOML file {path}",
                file=sys.stderr,
            )
            return None
        deps = data.get("dependencies", [])
        if not isinstance(deps, list):
            print(
                f"Error: 'dependencies' in {path} must be a list.",
                file=sys.stderr,
            )
            return None
        return deps
    except (OSError, UnicodeError) as e:
        print(f"Error: Failed to read {path}: {e}", file=sys.stderr)
        return None
    except Exception as e:
        print(f"Error: Failed to parse TOML in {path}: {e}", file=sys.stderr)
        return None


def parse_pep723(path: str) -> list[str] | None:
    """Parses an inline PEP 723 script metadata block from a Python file.

    Args:
        path: Path to the Python script file.

    Returns:
        List of dependency requirement strings, or None if parsing failed.
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
    except (OSError, UnicodeError) as e:
        print(f"Error: Failed to read {path}: {e}", file=sys.stderr)
        return None

    lines = content.splitlines()
    in_block = False
    block_lines: list[str] = []
    has_open_tag = False
    found_closing_tag = False

    for line in lines:
        stripped = line.strip()
        if not in_block:
            if re.match(r"^#\s*///\s*(script|vpython)\s*$", stripped):
                in_block = True
                has_open_tag = True
        else:
            if re.match(r"^#\s*///$", stripped):
                in_block = False
                found_closing_tag = True
                break
            block_lines.append(line)

    if has_open_tag and not found_closing_tag:
        print(
            f"Error: Malformed PEP 723 block (missing closing '# ///') in {path}",
            file=sys.stderr,
        )
        return None

    if not has_open_tag:
        return []

    toml_lines = []
    for line in block_lines:
        stripped = line.lstrip()
        if stripped.startswith("#"):
            toml_lines.append(re.sub(r"^# ?", "", stripped))
        else:
            print(
                f"Error: Non-comment line in PEP 723 block in {path}: {line}",
                file=sys.stderr,
            )
            return None
    toml_content = "\n".join(toml_lines)

    if tomllib is None:
        print("Error: tomllib module not available.", file=sys.stderr)
        return None
    try:
        data = tomllib.loads(toml_content)
        if not isinstance(data, dict):
            print(
                f"Error: Expected dictionary root in PEP 723 block in {path}",
                file=sys.stderr,
            )
            return None
        deps = data.get("dependencies", [])
        if not isinstance(deps, list):
            print(
                f"Error: 'dependencies' in PEP 723 block in {path} must be a list.",
                file=sys.stderr,
            )
            return None
        return deps
    except Exception as e:
        print(
            f"Error: Failed to parse PEP 723 inline TOML in {path}: {e}",
            file=sys.stderr,
        )
        return None


def parse_uv_lock(path: str) -> dict[str, list[str]] | None:
    """Parses a uv.lock file and maps package names to lists of locked versions.

    Args:
        path: Path to the uv.lock file.

    Returns:
        Dict mapping normalized package names to lists of locked version strings,
        or None if the lockfile is missing or invalid.
    """
    if not os.path.exists(path):
        return None

    # First attempt TOML parsing (standard uv.lock format)
    if tomllib is not None:
        try:
            with open(path, "rb") as f:
                data = tomllib.load(f)
            if not isinstance(data, dict):
                print(
                    f"Error: Expected dictionary root in lockfile {path}",
                    file=sys.stderr,
                )
                return None

            deps: dict[str, list[str]] = {}
            packages = data.get("package", [])
            if isinstance(packages, list):
                for pkg in packages:
                    if (
                        isinstance(pkg, dict)
                        and "name" in pkg
                        and "version" in pkg
                    ):
                        name = normalize_name(str(pkg["name"]))
                        ver = str(pkg["version"])
                        deps.setdefault(name, []).append(ver)
            return deps
        except (
            getattr(tomllib, "TOMLDecodeError", Exception),
            ValueError,
            TypeError,
        ) as e:
            try:
                with open(path, "r", encoding="utf-8", errors="ignore") as f:
                    raw_content = f.read()
                if "[[package]]" in raw_content or "version =" in raw_content:
                    print(
                        f"Error: Failed to parse TOML in lockfile {path}: {e}",
                        file=sys.stderr,
                    )
                    return None
            except Exception:
                pass

    # If tomllib is absent, check if file contains TOML structure
    try:
        with open(path, "r", encoding="utf-8") as f:
            content = f.read()
    except (OSError, UnicodeError) as e:
        print(f"Error: Failed to read {path}: {e}", file=sys.stderr)
        return None

    if tomllib is None and ("[[package]]" in content or "version =" in content):
        print(
            f"Error: Cannot parse TOML lockfile {path} because tomllib module is unavailable.",
            file=sys.stderr,
        )
        return None

    # Fallback to requirements.txt-style parsing
    lines = []
    current_line = []
    for line in content.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        if line.endswith("\\"):
            current_line.append(line[:-1].strip())
        else:
            current_line.append(line)
            lines.append(" ".join(current_line))
            current_line = []
    if current_line:
        lines.append(" ".join(current_line))

    fallback_deps: dict[str, list[str]] = {}
    for line in lines:
        pkg_spec = line.split(";")[0].split("--")[0].strip()
        if "==" in pkg_spec:
            name, ver = pkg_spec.split("==", 1)
            name = normalize_name(name.strip())
            fallback_deps.setdefault(name, []).append(ver.strip())

    return fallback_deps


def verify(spec_path: str, lock_path: str) -> int:
    """Verifies that a spec file's declared dependencies are satisfied in lock_path.

    Args:
        spec_path: Path to vpython.toml or PEP 723 script file.
        lock_path: Path to companion .uv.lock file.

    Returns:
        0 on verification success, 1 on verification error or out-of-sync.
    """
    if not os.path.exists(spec_path) and not os.path.exists(lock_path):
        # Both spec and lockfile were deleted in CL; nothing to verify.
        return 0

    if not os.path.exists(spec_path):
        print(f"Error: Spec file not found at {spec_path}", file=sys.stderr)
        return 1

    if spec_path.endswith(".py"):
        toml_deps = parse_pep723(spec_path)
    else:
        toml_deps = parse_vpython_toml(spec_path)

    if toml_deps is None:
        return 1

    if not toml_deps:
        return 0

    lock_deps = parse_uv_lock(lock_path)
    if lock_deps is None:
        print(
            f"Error: Lockfile {lock_path} is missing or invalid!",
            file=sys.stderr,
        )
        return 1

    out_of_sync = False
    errors: list[str] = []

    for dep in toml_deps:
        if not isinstance(dep, str):
            errors.append(
                f"Invalid dependency entry (expected string, got {type(dep).__name__}): {dep}"
            )
            out_of_sync = True
            continue

        if (
            Requirement is not None
            and SpecifierSet is not None
            and Version is not None
        ):
            try:
                req = Requirement(dep)
                name = normalize_name(req.name)
                if name not in lock_deps:
                    errors.append(
                        f"Package '{name}' is in spec but missing from lockfile"
                    )
                    out_of_sync = True
                    continue

                locked_versions = lock_deps[name]
                satisfied = False
                for ver_str in locked_versions:
                    try:
                        if req.specifier.contains(
                            Version(ver_str), prereleases=True
                        ):
                            satisfied = True
                            break
                    except Exception:
                        pass

                if not satisfied:
                    errors.append(
                        f"No locked version of '{name}' ({locked_versions}) satisfies requirement '{dep}'"
                    )
                    out_of_sync = True
                continue
            except Exception:
                pass

        # Fallback manual requirement parsing
        match = re.match(r"^([^>=<!~;@]+)(.*)$", dep)
        if not match:
            errors.append(f"Invalid dependency format in spec: {dep}")
            out_of_sync = True
            continue

        name = normalize_name(match.group(1).strip())
        spec = match.group(2).strip()

        if name not in lock_deps:
            errors.append(
                f"Package '{name}' is in spec but missing from lockfile"
            )
            out_of_sync = True
            continue

        locked_versions = lock_deps[name]

        if spec:
            spec_no_marker = spec.split(";")[0].strip()
            clauses = [
                c.strip() for c in spec_no_marker.split(",") if c.strip()
            ]
            satisfied = False
            for locked_ver in locked_versions:
                clause_ok = True
                for clause in clauses:
                    if clause.startswith("@"):
                        # PEP 508 Direct Reference URL requirement
                        continue
                    spec_match = re.match(r"^([>=<!~]+)(.*)$", clause)
                    if spec_match:
                        op = spec_match.group(1).strip()
                        req_ver = spec_match.group(2).strip()
                        if not compare_versions(locked_ver, op, req_ver):
                            clause_ok = False
                            break
                    else:
                        clause_ok = False
                        break
                if clause_ok:
                    satisfied = True
                    break

            if not satisfied:
                errors.append(
                    f"No locked version of '{name}' ({locked_versions}) satisfies requirement '{dep}'"
                )
                out_of_sync = True

    if out_of_sync:
        print(
            f"Spec and lockfile {os.path.basename(lock_path)} are OUT OF SYNC:",
            file=sys.stderr,
        )
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        print(
            f"\nTo resolve this, update {os.path.basename(lock_path)} using 'uv pip compile' or vpython tooling.",
            file=sys.stderr,
        )
        return 1

    print(f"Spec and lockfile {os.path.basename(lock_path)} are IN SYNC")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print(
            "Usage: verify_lockfile.py <spec_file> <lock_file>", file=sys.stderr
        )
        sys.exit(1)
    sys.exit(verify(sys.argv[1], sys.argv[2]))
